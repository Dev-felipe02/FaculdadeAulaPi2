let nota = 7.5;

if(nota < 6){

    console.log("Insuficiente.");

}else if(nota >= 6 || nota < 7){

    console.log("Regular.");

}else if(nota >= 7 && nota < 9){

    console.log("Bom.");

}else if(nota > 9 && nota < 11){

    console.log("Excelente.");

}else {

console.log("Nota invalida.");

}